#!/usr/bin/env node

/**
 * sync-api-types.mjs
 *
 * Fetches the OpenAPI spec from the Derby Scoreboard API and generates
 * TypeScript interfaces from its component schemas.
 *
 * Usage:
 *   node scripts/sync-api-types.mjs
 *   API_URL=http://some-host:9999 node scripts/sync-api-types.mjs
 */

import { writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

const DEFAULT_API_URL = "http://localhost:5001/openapi.json";
const apiUrl = process.env.API_URL ?? DEFAULT_API_URL;

// Resolve output path relative to *this* script, not the working directory.
const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = resolve(
  __dirname,
  "..",
  "apps",
  "live-tracker",
  "src",
  "types",
  "scoreboard-api.ts",
);

/** Dependency-ordered list of schema names to emit. */
const SCHEMA_ORDER = ["SkaterPosition", "TeamState", "LiveState", "HealthState"];

const FILE_HEADER = `\
/**
 * Auto-generated TypeScript types for the Derby Scoreboard API.
 *
 * Source of truth: derby-scoreboard-api/models.py (Pydantic models)
 * OpenAPI spec:    http://localhost:5001/openapi.json
 *
 * To regenerate:   npm run sync:api-types
 * Do NOT edit this file by hand — changes will be overwritten.
 */

`;

// ---------------------------------------------------------------------------
// OpenAPI → TypeScript helpers
// ---------------------------------------------------------------------------

/**
 * Convert an OpenAPI property schema to its TypeScript type string.
 */
function resolveType(prop) {
  if (!prop) return "unknown";

  // $ref → named type
  if (prop.$ref) {
    return refToName(prop.$ref);
  }

  // anyOf — the typical Pydantic "Optional[X]" representation:
  //   anyOf: [ { type: X }, { type: "null" } ]
  //   or anyOf: [ { $ref: "..." }, { type: "null" } ]
  if (Array.isArray(prop.anyOf)) {
    const nonNull = prop.anyOf.filter((v) => v.type !== "null");
    const hasNull = prop.anyOf.some((v) => v.type === "null");
    const types = nonNull.map((v) => resolveType(v));
    if (hasNull) types.push("null");
    return types.join(" | ") || "unknown";
  }

  // allOf with a single entry (another Pydantic pattern for nested models)
  if (Array.isArray(prop.allOf) && prop.allOf.length === 1) {
    return resolveType(prop.allOf[0]);
  }

  // Primitive types
  switch (prop.type) {
    case "boolean":
      return "boolean";
    case "integer":
    case "number":
      return "number";
    case "string":
      return "string";
    case "array":
      return `${resolveType(prop.items)}[]`;
    case "object":
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

/**
 * Extract the schema name from a JSON-pointer $ref string.
 * e.g. "#/components/schemas/SkaterPosition" → "SkaterPosition"
 */
function refToName(ref) {
  const parts = ref.split("/");
  return parts[parts.length - 1];
}

/**
 * Build a JSDoc block for a property, including description and default value.
 * Returns an array of lines (without trailing newline), or an empty array if
 * there is nothing to document.
 */
function buildJsDoc(prop, indent = "  ") {
  const lines = [];

  if (prop.description) {
    // Wrap long descriptions that may contain newlines
    for (const descLine of prop.description.split("\n")) {
      lines.push(`${indent} * ${descLine.trimEnd()}`);
    }
  }

  if (prop.default !== undefined) {
    const formatted =
      typeof prop.default === "string"
        ? `"${prop.default}"`
        : JSON.stringify(prop.default);
    lines.push(`${indent} * @default ${formatted}`);
  }

  if (lines.length === 0) return [];

  return [`${indent}/**`, ...lines, `${indent} */`];
}

/**
 * Convert a single OpenAPI component schema into a TypeScript interface string.
 */
function schemaToInterface(name, schema) {
  const lines = [];

  // Interface-level JSDoc
  if (schema.description) {
    lines.push("/**");
    for (const descLine of schema.description.split("\n")) {
      lines.push(` * ${descLine.trimEnd()}`);
    }
    lines.push(" */");
  }

  lines.push(`export interface ${name} {`);

  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);

  for (const [propName, prop] of Object.entries(properties)) {
    const jsdoc = buildJsDoc(prop);
    if (jsdoc.length > 0) {
      lines.push(...jsdoc);
    }

    const tsType = resolveType(prop);
    const optional = !required.has(propName);
    const questionMark = optional ? "?" : "";

    lines.push(`  ${propName}${questionMark}: ${tsType};`);
  }

  lines.push("}");
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  // 1. Fetch the OpenAPI spec
  let spec;
  try {
    const res = await fetch(apiUrl);
    if (!res.ok) {
      throw new Error(`HTTP ${res.status} ${res.statusText}`);
    }
    spec = await res.json();
  } catch (err) {
    console.error(`❌  Failed to fetch OpenAPI spec from ${apiUrl}`);
    console.error(`    ${err.message}`);
    console.error(
      `\n    Is the scoreboard API running on port 5001?\n` +
        `    You can also set API_URL to point to a different host.\n`,
    );
    process.exit(1);
  }

  // 2. Read component schemas
  const schemas = spec?.components?.schemas;
  if (!schemas) {
    console.error("❌  OpenAPI spec has no components.schemas — nothing to generate.");
    process.exit(1);
  }

  // 3. Verify all expected schemas exist
  for (const name of SCHEMA_ORDER) {
    if (!schemas[name]) {
      console.error(
        `❌  Expected schema "${name}" not found in OpenAPI spec. ` +
          `Available schemas: ${Object.keys(schemas).join(", ")}`,
      );
      process.exit(1);
    }
  }

  // 4. Convert schemas to TypeScript in dependency order
  const interfaceBlocks = SCHEMA_ORDER.map((name) =>
    schemaToInterface(name, schemas[name]),
  );

  const output = FILE_HEADER + interfaceBlocks.join("\n\n") + "\n";

  // 5. Ensure output directory exists & write file
  try {
    await mkdir(dirname(OUTPUT_PATH), { recursive: true });
    await writeFile(OUTPUT_PATH, output, "utf-8");
  } catch (err) {
    console.error(`❌  Failed to write output file: ${OUTPUT_PATH}`);
    console.error(`    ${err.message}`);
    process.exit(1);
  }

  console.log(
    `✅  Generated ${interfaceBlocks.length} interface(s) → ${OUTPUT_PATH}`,
  );
}

main();
